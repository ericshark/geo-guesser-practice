import type { LanguageGroupId, LanguageSample, LanguageSpec, TellSpec } from './types.ts';

/**
 * Drills for languages that countries use but the first set of drills left out.
 * Rows are [kind, text, English meaning]. Ids are generated (`<lang>-sent-N`, `<lang>-sign-N`) and
 * every tell is offered for every sample; the content layer keeps only the tells that really occur
 * in the text, so highlights stay verifiable.
 * Samples are everyday street, shopfront and notice wording written for this app (no copied text).
 */
type Row = ['sign' | 'sentence', string, string];

function samplesOf(lang: string, tells: TellSpec[], rows: Row[]): LanguageSample[] {
  let sentence = 0;
  let sign = 0;
  return rows.map(([kind, text, translation]) => ({
    id: kind === 'sentence' ? `${lang}-sent-${++sentence}` : `${lang}-sign-${++sign}`,
    text,
    translation,
    kind,
    tellIds: tells.map((t) => t.id),
  }));
}

interface Def {
  id: string;
  name: string;
  nativeName: string;
  groupId: LanguageGroupId;
  script: string;
  tells: TellSpec[];
  gestaltNote: string;
  contrastNote: string;
  candidateCountryIds: string[];
  uncoveredCountryIds?: string[];
  uncoveredCountryNotes: string[];
  rows: Row[];
}

function build({ rows, ...def }: Def): LanguageSpec {
  return { ...def, samples: samplesOf(def.id, def.tells, rows) };
}

