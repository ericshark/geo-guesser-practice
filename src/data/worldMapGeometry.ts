/**
 * Generates a fallback bounding polygon around a country's coordinates if not in COUNTRY_LAT_LON_RINGS.
 */
function buildFallbackRing(country: PlayableCountry): Array<Array<[number, number]>> {
  const [lat, lon] = country.coordinates;
  const dLat = country.isTerritory ? 0.35 : 1.5;
  const dLon = country.isTerritory ? 0.45 : 1.8;
  return [
    [
      [lat - dLat, lon - dLon],
      [lat + dLat, lon - dLon],
      [lat + dLat, lon + dLon],
      [lat - dLat, lon + dLon],
    ],
  ];
}

