// Natural Earth Admin 0 Map Units, 1:50m, v5.1.1 (public domain).
// Run from the repository root with Node 24:
//   node scripts/generate-atlas.mjs /path/to/ne_50m_admin_0_map_units.geojson
// Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.1/geojson/ne_50m_admin_0_map_units.geojson
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { PLAYABLE_COUNTRIES } from '../src/data/countries.ts';
import { projectLatLonToSvg } from '../src/data/mapProjection.ts';

const source = readFileSync(process.argv[2]);
const expectedHash = 'b8d421aca6e9e08e8cdf09cc26af111cc3e0deba4fe915611d58ade71e8a4db0';
if (createHash('sha256').update(source).digest('hex') !== expectedHash) {
  throw new Error('Expected the pinned Natural Earth v5.1.1 GeoJSON.');
}

const playableIds = new Set(PLAYABLE_COUNTRIES.map(({ id }) => id));
const countryPaths = new Map();
const contextPaths = [];

// ISO_A2_EH groups mainland subunits and distinguishes overseas territories.
// Natural Earth models Jan Mayen and the Australian Antarctic claim as map units.
const mapUnitOverrides = new Map([
  ['NJM', 'no'],
  ['ATC', null],
]);

function ringPath(ring) {
  const points = [];
  for (let index = 0; index < ring.length - 1; index++) {
    const [lon, lat] = ring[index];
    // The pinned source already cuts polygons at the date line.
    if (Math.abs(lon - ring[index + 1][0]) > 180) {
      throw new Error('Found a ring with an uncut date-line crossing.');
    }
    const point = projectLatLonToSvg(lat, lon);
    const previous = points.at(-1);
    if (!previous || point[0] !== previous[0] || point[1] !== previous[1]) points.push(point);
  }
  if (new Set(points.map((point) => point.join(' '))).size < 3) return '';
  const relativeSteps = points.slice(1).map(([x, y], index) => {
    const [previousX, previousY] = points[index];
    return `${Number((x - previousX).toFixed(1))} ${Number((y - previousY).toFixed(1))}`;
  });
  return `M${points[0].join(' ')}l${relativeSteps.join(' ')}Z`;
}

for (const { properties, geometry } of JSON.parse(source).features) {
  const id = mapUnitOverrides.has(properties.GU_A3)
    ? mapUnitOverrides.get(properties.GU_A3)
    : properties.ISO_A2_EH.toLowerCase();
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  const path = polygons.map(([outer, ...holes]) => {
    const outline = ringPath(outer);
    return outline ? outline + holes.map(ringPath).join('') : '';
  }).join('');
  if (!path) continue;
  if (playableIds.has(id)) {
    countryPaths.set(id, (countryPaths.get(id) ?? '') + path);
  } else {
    contextPaths.push(path);
  }
}

for (const country of PLAYABLE_COUNTRIES) {
  if (!countryPaths.has(country.id) && !country.isTerritory) {
    throw new Error(`Missing geometry for ${country.name}.`);
  }
}

const output = [
  '// Generated by scripts/generate-atlas.mjs from Natural Earth v5.1.1 (public domain).',
  'export const ATLAS_COUNTRY_PATHS: Partial<Record<string, string>> = ' +
    JSON.stringify(Object.fromEntries([...countryPaths].sort()), null, 2) + ';',
  'export const ATLAS_CONTEXT_PATH = ' + JSON.stringify(contextPaths.join('')) + ';',
  '',
].join('\n');

writeFileSync(new URL('../src/data/atlasPaths.ts', import.meta.url), output);
